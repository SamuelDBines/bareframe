#!/usr/bin/env node
/**
 * Generates prototype/src/components/library/doc-meta.ts from doc-example-spec.json
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const spec = JSON.parse(
	readFileSync(path.join(root, 'prototype/src/components/library/doc-example-spec.json'), 'utf8'),
);

const CATEGORY_TOKENS = {
	Display: ['--bf-theme-surface-1', '--bf-theme-text', '--bf-theme-border-color'],
	Actions: ['--bf-theme-primary', '--bf-theme-primary-fg', '--bf-theme-radius-md'],
	Forms: ['--bf-theme-border-color', '--bf-theme-surface-1', '--bf-theme-focus-ring'],
	Feedback: ['--bf-theme-alert-bg', '--bf-theme-alert-border-color', '--bf-theme-surface-1'],
	Overlays: ['--bf-theme-surface-2', '--bf-theme-shadow-lg', '--bf-theme-border-color'],
	Navigation: ['--bf-theme-text', '--bf-theme-surface-1', '--bf-theme-primary'],
	'Data display': ['--bf-theme-surface-1', '--bf-theme-text-muted', '--bf-theme-border-color'],
	'Date & time': ['--bf-theme-surface-1', '--bf-theme-primary', '--bf-theme-border-color'],
};

/** Slug -> category from registry (static map) */
const SLUG_CATEGORY = {
	alert: 'Feedback',
	badge: 'Display',
	button: 'Actions',
	card: 'Display',
	checkbox: 'Forms',
	switch: 'Forms',
	field: 'Forms',
	input: 'Forms',
	textarea: 'Forms',
	select: 'Forms',
	slider: 'Forms',
	'radio-group': 'Forms',
	multiselect: 'Forms',
	combobox: 'Forms',
	modal: 'Overlays',
	drawer: 'Overlays',
	tooltip: 'Overlays',
	popover: 'Overlays',
	'dropdown-menu': 'Overlays',
	tabs: 'Navigation',
	breadcrumbs: 'Navigation',
	pagination: 'Navigation',
	accordion: 'Navigation',
	toast: 'Feedback',
	progress: 'Feedback',
	spinner: 'Feedback',
	skeleton: 'Feedback',
	avatar: 'Data display',
	table: 'Data display',
	'empty-state': 'Data display',
	'stat-card': 'Data display',
	calendar: 'Date & time',
	datepicker: 'Date & time',
};

const OVERVIEW = {
	alert: 'Alerts communicate important feedback inline — success, warnings, errors, or neutral info — without blocking the whole page.',
	badge: 'Badges label status, counts, and metadata in compact chips.',
	button: 'Buttons trigger actions with clear hierarchy across primary, secondary, ghost, and destructive styles.',
	card: 'Cards group related content with optional titles, footers, and elevation.',
	tabs: 'Tabs organize peer views at the same level of hierarchy with keyboard support.',
	accordion: 'Accordions reveal progressive disclosure for FAQs and dense settings.',
	combobox: 'Comboboxes combine typeahead filtering with a single selection list.',
	multiselect: 'MultiSelect collects many values with removable chips and an add control.',
};

function titleCase(slug) {
	return slug
		.split('-')
		.map((w) => w.charAt(0).toUpperCase() + w.slice(1))
		.join(' ');
}

/** @type {Record<string, object>} */
const meta = {};

for (const slug of Object.keys(spec)) {
	const samples = spec[slug].samples;
	const category = SLUG_CATEGORY[slug] ?? 'Display';
	const name = slug === 'radio-group' ? 'Radio group' : slug === 'empty-state' ? 'Empty state' : slug === 'stat-card' ? 'Stat card' : slug === 'dropdown-menu' ? 'Dropdown menu' : titleCase(slug);
	meta[slug] = {
		overview:
			OVERVIEW[slug] ??
			`${name} is part of Bareframe’s accessible React kit — styled with \`--bf-theme-*\` tokens and React Aria where appropriate.`,
		whenToUse:
			slug === 'toast'
				? 'Use for transient global notices; prefer Alert for inline contextual feedback.'
				: `Use ${name.toLowerCase()} when the pattern matches your layout and accessibility needs.`,
		docExamples: samples.map((s) => ({
			title: s.title,
			file: s.file,
			description: s.description,
		})),
		dosDonts: [
			{
				do: `Keep ${name.toLowerCase()} usage consistent with surrounding typography and spacing tokens.`,
				dont: 'Hard-code colors that bypass theme variables.',
			},
			{
				do: 'Provide visible labels and keyboard paths for interactive controls.',
				dont: 'Rely on placeholder text alone for critical context.',
			},
		],
		themeTokens: CATEGORY_TOKENS[category] ?? CATEGORY_TOKENS.Display,
	};
}

const out = `/** Auto-generated by scripts/generate-doc-meta.mjs — do not edit manually. */
import type { DocExample, DosDont } from './types';

export type DocMeta = {
	overview: string;
	whenToUse: string;
	docExamples: DocExample[];
	dosDonts: DosDont[];
	themeTokens: string[];
};

export const DOC_META: Record<string, DocMeta> = ${JSON.stringify(meta, null, '\t')} as Record<string, DocMeta>;
`;

writeFileSync(path.join(root, 'prototype/src/components/library/doc-meta.ts'), out);
console.log('Wrote doc-meta.ts for', Object.keys(meta).length, 'components');

import { spawnSync } from 'node:child_process';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { categoryForSlug } from './component-categories.mjs';
import { extractComponentParts } from './extract-studio-style-hints.mjs';
import { build } from 'esbuild';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const root = path.resolve(__dirname, '..');
const srcDir = path.join(root, 'src');
const themesDir = path.join(root, 'themes');
/** Publishable library output (npm `files: ["dist"]`). Synced to `public/dist` by `prep-pages.mjs`. */
const distDir = path.join(root, 'dist');
const distComponentsDir = path.join(distDir, 'components');
const distThemesDir = path.join(distDir, 'themes');

const stencilSrcComponents = path.join(root, 'stencil', 'src', 'components');

function stencilSlugFromBfFile(fileName) {
	const m = /^bf-([\w-]+)\.js$/.exec(fileName);
	return m ? m[1] : null;
}

function parseArgs(argv) {
	const args = { devOutfile: path.join(distDir, 'index.js') };
	for (let i = 0; i < argv.length; i += 1) {
		const arg = argv[i];
		if (arg === '--dev-outfile') {
			const next = argv[i + 1];
			if (!next) {
				throw new Error('Missing value for --dev-outfile');
			}
			args.devOutfile = path.resolve(root, next);
			i += 1;
		}
	}
	return args;
}

async function exists(filePath) {
	try {
		await fs.access(filePath);
		return true;
	} catch {
		return false;
	}
}

async function resolveIndexEntry() {
	for (const ext of ['.ts', '.js']) {
		const candidate = path.join(srcDir, `index${ext}`);
		if (await exists(candidate)) {
			return candidate;
		}
	}
	throw new Error('Missing src/index.ts or src/index.js');
}

async function cleanAndPrepareDist() {
	await fs.rm(distDir, { recursive: true, force: true });
	await fs.mkdir(distComponentsDir, { recursive: true });
	await fs.mkdir(distThemesDir, { recursive: true });
}

function runStencilBuild() {
	const stencilDir = path.join(root, 'stencil');
	const cmd = process.platform === 'win32' ? 'pnpm.cmd' : 'pnpm';
	const r = spawnSync(cmd, ['exec', 'stencil', 'build'], {
		cwd: stencilDir,
		stdio: 'inherit',
		env: process.env,
	});
	if (r.error) {
		throw r.error;
	}
	if (r.status !== 0) {
		throw new Error(`Stencil build failed (exit ${r.status}).`);
	}
}

async function listStencilBfFiles() {
	const stencilOut = path.join(distDir, '_stencil');
	const names = await fs.readdir(stencilOut);
	return names.filter((n) => /^bf-[\w-]+\.js$/.test(n));
}

async function writeStencilBundleSource() {
	const stencilIndexPath = path.join(distDir, '_stencil', 'index.js');
	const txt = await fs.readFile(stencilIndexPath, 'utf8');
	const fns = [
		...txt.matchAll(/defineCustomElement as (defineCustomElementBf\w+)/g),
	].map((m) => m[1]);
	const uniq = [...new Set(fns)].sort();

	const imports = uniq.join(',\n  ');
	const arr = uniq.join(',\n  ');
	const bundleSrc = `// @ts-nocheck
/**
 * Registers every Stencil-built custom element when the barrel bundle loads.
 * This file is generated by scripts/build.mjs whenever you run the build — do not edit by hand.
 */
import {
  ${imports}
} from '../dist/_stencil/index.js';

const _registry = [\n  ${arr}\n] as const;

for (const define of _registry) {
	define();
}
`;
	await fs.writeFile(path.join(srcDir, 'stencil-bundle.ts'), bundleSrc);
}

async function copyStencilComponentArtifacts() {
	const stencilOut = path.join(distDir, '_stencil');
	const names = await fs.readdir(stencilOut);
	for (const fn of names) {
		if (!fn.endsWith('.js') || fn === 'index.js') {
			continue;
		}
		await fs.copyFile(
			path.join(stencilOut, fn),
			path.join(distComponentsDir, fn),
		);
	}

	for (const fn of names) {
		const slug = stencilSlugFromBfFile(fn);
		if (!slug) {
			continue;
		}
		const registerShim = `import { defineCustomElement } from './${fn}';

defineCustomElement();
`;

		await fs.writeFile(path.join(distComponentsDir, `${slug}.js`), registerShim);

		const tag = `bf-${slug}`;
		const cssFromStencil = path.join(stencilSrcComponents, tag, `${tag}.css`);
		if (await exists(cssFromStencil)) {
			await fs.copyFile(cssFromStencil, path.join(distComponentsDir, `${slug}.css`));
		}
	}
}

async function copyThemes() {
	const entries = await fs.readdir(themesDir, { withFileTypes: true });
	for (const entry of entries) {
		if (!entry.isFile() || !entry.name.endsWith('.css')) {
			continue;
		}
		await fs.copyFile(
			path.join(themesDir, entry.name),
			path.join(distThemesDir, entry.name),
		);
	}
}

async function writeManifest(slugs) {
	const manifest = {
		generatedAt: new Date().toISOString(),
		componentCount: slugs.length,
		components: slugs,
	};
	await fs.writeFile(
		path.join(distDir, 'manifest.json'),
		`${JSON.stringify(manifest, null, 2)}\n`,
	);
}

async function writeShowcaseStudioMetadata(slugs) {
	const categories = Object.fromEntries(slugs.map((s) => [s, categoryForSlug(s)]));
	const parts = await extractComponentParts(slugs, stencilSrcComponents);
	const payload = {
		generatedAt: new Date().toISOString(),
		categories,
		parts,
	};
	await fs.writeFile(
		path.join(distDir, 'showcase-studio.json'),
		`${JSON.stringify(payload, null, 2)}\n`,
	);
	console.log('Wrote dist/showcase-studio.json (categories + ::part hints).');
}

/** Extract `--name` custom properties from flattened CSS text (handles minified blocks). */
function extractCssCustomPropertyNames(cssText) {
	const names = new Set();
	const re = /--[\w-]+/g;
	let m = re.exec(cssText);
	while (m !== null) {
		const raw = m[0];
		// Exclude gradient stops / vendor-like noise (--webkit-…) if any
		if (raw.startsWith('--bf-')) {
			names.add(raw);
		}
		m = re.exec(cssText);
	}
	return [...names].sort();
}

async function flattenThemeImports(themePath, themesRoot, seen = new Set()) {
	const canon = path.resolve(themePath);
	if (seen.has(canon)) {
		return '';
	}
	seen.add(canon);

	let body = await fs.readFile(themePath, 'utf8');
	const dir = path.dirname(themePath);

	// Replace @import url('x') / @import "x";
	const importRe =
		/@import\s+(?:url\(\s*(['"])([^'"]+)\1\s*\)|(['"])([^'"]+)\3)\s*;/g;
	let out = '';
	let lastIdx = 0;
	let mm = importRe.exec(body);

	while (mm !== null) {
		const before = body.slice(lastIdx, mm.index);
		out += before;

		const rel = mm[2] || mm[4];
		if (!rel || rel.startsWith('http') || rel.startsWith('//')) {
			out += mm[0];
		} else {
			const importedPath = path.resolve(dir, rel);
			out += await flattenThemeImports(importedPath, themesRoot, seen);
		}

		lastIdx = importRe.lastIndex;
		mm = importRe.exec(body);
	}
	out += body.slice(lastIdx);
	return out;
}

async function generateTokensManifest() {
	const entries = await fs.readdir(themesDir, { withFileTypes: true });
	const cssFiles = entries.filter((e) => e.isFile() && e.name.endsWith('.css'));

	const themes = {};
	const allTokens = new Set();

	for (const e of cssFiles.sort((a, b) => a.name.localeCompare(b.name))) {
		const filePath = path.join(themesDir, e.name);
		const flattened = await flattenThemeImports(filePath, themesDir);
		const names = extractCssCustomPropertyNames(flattened);
		themes[path.basename(e.name, '.css')] = names;
		for (const n of names) {
			allTokens.add(n);
		}
	}

	const payload = {
		generatedAt: new Date().toISOString(),
		tokens: [...allTokens].sort(),
		byTheme: themes,
	};
	await fs.writeFile(
		path.join(distDir, 'tokens.json'),
		`${JSON.stringify(payload, null, 2)}\n`,
	);
	console.log(`Wrote tokens manifest (${payload.tokens.length} unique --bf-* tokens).`);
}

async function writeBundles(outfile, minify) {
	const entryPoint = await resolveIndexEntry();
	await build({
		entryPoints: [entryPoint],
		bundle: true,
		format: 'esm',
		target: ['es2020'],
		minify,
		outfile,
	});
}

async function main() {
	const args = parseArgs(process.argv.slice(2));
	await cleanAndPrepareDist();
	runStencilBuild();
	await writeStencilBundleSource();
	await copyStencilComponentArtifacts();

	const stencilFiles = await listStencilBfFiles();
	const stencilSlugs = stencilFiles
		.map(stencilSlugFromBfFile)
		.filter(Boolean)
		.sort();

	await copyThemes();
	await generateTokensManifest();

	await writeBundles(args.devOutfile, false);
	await writeManifest(stencilSlugs);
	await writeShowcaseStudioMetadata(stencilSlugs);
	await writeBundles(path.join(distDir, 'bareframe.min.js'), true);

	console.log(`Built bareframe (${stencilSlugs.length} Stencil components).`);
}

main().catch((error) => {
	console.error(error);
	process.exit(1);
});
